// A deliberately small CommonJS packer: only local static imports, no resolution magic.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../extension");
const modules = new Map();
function collect(filename) {
    const id = path.relative(root, filename).split(path.sep).join("/");
    if (modules.has(id)) return id;
    if (!filename.startsWith(root + path.sep)) throw new Error(`Import outside extension: ${filename}`);
    let source = fs.readFileSync(filename, "utf8");
    modules.set(id, "");
    source = source.replace(/require\(["'](\.[^"']+)["']\)/g, (_match, specifier) => {
        const dependency = path.resolve(path.dirname(filename), specifier);
        return `require(${JSON.stringify(collect(dependency))})`;
    });
    modules.set(id, source);
    return id;
}
function bundle(entryName, outputName) {
    modules.clear();
    const entry = collect(path.join(root, entryName));
    const output = `// Generated by scripts/build_extension.cjs. Edit source modules instead.\n(() => {\n"use strict";\nconst modules = {\n${[...modules].map(([id, source]) => `${JSON.stringify(id)}: (module, exports, require) => {\n${source}\n}`).join(",\n")}\n};\nconst cache = new Map();\nfunction require(id) {\n    if (cache.has(id)) return cache.get(id).exports;\n    const module = { exports: {} }; cache.set(id, module);\n    modules[id](module, module.exports, require); return module.exports;\n}\nrequire(${JSON.stringify(entry)});\n})();\n`;
    const target = path.join(root, outputName);
    if (process.argv.includes("--check")) {
        if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) throw new Error("Extension bundle is stale; run npm run build:extension");
    } else fs.writeFileSync(target, output);

}
bundle("content_entry.js", "content_runtime.js");
bundle("manager_entry.js", "manager_runtime.js");
